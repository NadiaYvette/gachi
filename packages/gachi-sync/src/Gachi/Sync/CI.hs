-- | Human-readable name of a 'ForgeType'.
--
-- Used in diagnostic banners and synchronization audit reports.
forgeName :: ForgeType -> Text
forgeName ForgeGitHub     = "GitHub Actions"
forgeName ForgeGitLab     = "GitLab CI (Framagit, Disroot)"
forgeName ForgeWoodpecker = "Woodpecker CI"
forgeName ForgeForgejo    = "Forgejo Actions"
forgeName ForgeRadicle    = "Radicle P2P CI"

-- | Human-readable description of a 'CITier'.
--
-- Highlights whether a pipeline executes heavyweight GHC verification or fast static gates.
tierName :: CITier -> Text
tierName TierHighResource      = "High-Resource (Full Physical Verification)"
tierName TierLightweightStatic = "Lightweight (Static Gates Only)"

-- | Predicate checking if a specification belongs to the high-resource tier.
isHighResource :: CISpec -> Bool
isHighResource spec = ciTier spec == TierHighResource

-- | Predicate checking if a specification belongs to the lightweight tier.
isLightweight :: CISpec -> Bool
isLightweight spec = ciTier spec == TierLightweightStatic

-- | Infers the 'ForgeType' from a workflow file path.
--
-- Inspects standard file names and directories:
-- * @.github/workflows/*@ -> 'ForgeGitHub'
-- * @.gitlab-ci.yml@ -> 'ForgeGitLab'
-- * @.woodpecker.yml@ or @.woodpecker/*@ -> 'ForgeWoodpecker'
-- * @.forgejo/workflows/*@ -> 'ForgeForgejo'
-- * @.radicle/*@ -> 'ForgeRadicle'
--
-- Returns 'Nothing' if the path does not match recognized CI conventions.
classifyForge :: FilePath -> Maybe ForgeType
classifyForge path
  -- GitHub Actions workflow directory
  | ".github/workflows/" `isPrefixOf` path = Just ForgeGitHub
  -- GitLab CI configuration file in root
  | path == ".gitlab-ci.yml"               = Just ForgeGitLab
  -- Woodpecker CI single file configuration
  | path == ".woodpecker.yml"              = Just ForgeWoodpecker
  -- Woodpecker CI pipeline directory
  | ".woodpecker/" `isPrefixOf` path       = Just ForgeWoodpecker
  -- Forgejo Actions workflow directory
  | ".forgejo/" `isPrefixOf` path          = Just ForgeForgejo
  -- Radicle P2P CI verification directory
  | ".radicle/" `isPrefixOf` path          = Just ForgeRadicle
  -- Unrecognized path
  | otherwise                              = Nothing

-- | Infers the expected 'CITier' from a standard workflow path.
--
-- Recognizes high-resource vs lightweight tiers based on repository path conventions.
classifyTier :: FilePath -> Maybe CITier
classifyTier path
  -- GitHub Actions executes full verification suite
  | ".github/" `isPrefixOf` path  = Just TierHighResource
  -- GitLab CI community runners execute static gates only
  | path == ".gitlab-ci.yml"      = Just TierLightweightStatic
  -- Woodpecker CI executes lightweight container steps
  | path == ".woodpecker.yml"     = Just TierLightweightStatic
  -- Forgejo enterprise runners execute full suite
  | ".forgejo/" `isPrefixOf` path = Just TierHighResource
  -- Radicle local node broker executes static gates
  | ".radicle/" `isPrefixOf` path = Just TierLightweightStatic
  -- Unrecognized path
  | otherwise                     = Nothing

