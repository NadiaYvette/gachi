-- 1. Forge and CI Tier Data Models
--------------------------------------------------------------------------------

-- | Target hosting forge or CI engine platform.
--
-- Distinguishes commercial clouds with abundant runner quotas from shared
-- community instances and sovereign peer-to-peer repositories.
--
-- Architectural Roles:
-- * 'ForgeGitHub': Commercial cloud runners with 4+ vCPUs, 16 GB RAM, caching.
-- * 'ForgeGitLab': Community shared runners with strict memory and CPU limits.
-- * 'ForgeWoodpecker': Lightweight container pipelines for Forgejo / Codeberg.
-- * 'ForgeForgejo': Self-hosted Git server workflows using Docker runners.
-- * 'ForgeRadicle': Sovereign peer-to-peer identity verification prior to sync.
data ForgeType
  = ForgeGitHub
    -- ^ GitHub Actions (@.github/workflows/ci.yml@): Commercial high-capacity runners.
  | ForgeGitLab
    -- ^ GitLab CI (@.gitlab-ci.yml@): Community runners (Framagit, Disroot, gitlab.com).
  | ForgeWoodpecker
    -- ^ Woodpecker CI (@.woodpecker.yml@): Lightweight container pipelines for Forgejo/Gitea.
  | ForgeForgejo
    -- ^ Forgejo / Gitea Actions (@.forgejo/workflows/ci.yml@): Self-hosted Git server workflows.
  | ForgeRadicle
    -- ^ Radicle P2P (@.radicle/ci.yaml@): Local verification broker for sovereign peer nodes.
  deriving stock (Eq, Show, Ord, Enum, Bounded, Generic)

-- | Resource capability tier assigned to a CI workflow pipeline.
--
-- Governs whether a forge executes the full heavyweight GHC build suite or
-- restricts execution to lightweight static verification gates.
--
-- The allocation strategy guarantees that high-resource runners handle compiler
-- overhead while community runners remain responsive and protected from OOM errors.
data CITier
  = TierHighResource
    -- ^ Heavyweight execution: Full GHC compilation, test suites, Cabal store caching,
    -- AppArmor namespace configuration, and complete physical verification script execution.
  | TierLightweightStatic
    -- ^ Lightweight execution: Fast static gates (Tagref, linkcheck, CLOC audit)
    -- inside a slim container without GHC compiler toolchains (< 15 seconds runtime).
  deriving stock (Eq, Show, Ord, Enum, Bounded, Generic)

-- | Declarative specification governing continuous integration generation.
--
-- Encapsulates the target platform, resource tier, filesystem workflow destination,
-- toolchain versions, container images, and test flags.
--
-- All fields are pure and deterministic, permitting total reproducibility.
data CISpec = CISpec
  { ciForge              :: !ForgeType
    -- ^ Target hosting forge or runner platform.
  , ciTier               :: !CITier
    -- ^ Resource tier governing execution depth (high-resource vs lightweight).
  , ciWorkflowPath       :: !FilePath
    -- ^ Relative workflow path in repository root (e.g. @".github/workflows/ci.yml"@).
  , ciGhcVersion         :: !Text
    -- ^ Target GHC compiler version string (e.g. @"9.14.1"@).
  , ciCabalVersion       :: !Text
    -- ^ Target Cabal specification version string (e.g. @"3.18.1.0"@).
  , ciSystemDependencies :: ![Text]
    -- ^ System apt packages required by high-resource builds (e.g. @["bubblewrap", "sqlite3", "z3"]@).
  , ciContainerImage     :: !Text
    -- ^ Minimal container image for lightweight static runners (e.g. @"debian:bookworm-slim"@).
  , ciEnableTests        :: !Bool
    -- ^ Whether to configure @--enable-tests@ during Cabal compilation.
  , ciEnableDocCheck     :: !Bool
    -- ^ Whether to perform comment density and documentation verification.
  } deriving stock (Eq, Show, Generic)

