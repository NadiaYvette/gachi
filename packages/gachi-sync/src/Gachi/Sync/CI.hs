-- | Module: Gachi.Sync.CI
-- Description: Forge-tiered CI matrix synthesis and asymmetric runner resource allocation
--
-- This module implements Milestone 3.3 of the Gachi strategic roadmap (~/src/PLAN.md §1.A).
-- It provides pure declarative models and deterministic generators for multi-forge
-- continuous integration (CI) workflows, partitioning physical verification gates
-- across asymmetric runner capabilities.
--
-- = Architectural Context & Invariants
--
-- In accordance with Note [Ecosystem Standardization Invariants]
-- [ref:note-ecosystem-standardization], Note [Cross-Repository Standardization Matrix and Audit Semantics]
-- [ref:note-standardization-matrix], and Note [Forge-Tiered CI Resource Allocation and Static Gate Partitioning]
-- [ref:note-forge-tiered-ci], ecosystem repositories replicate across heterogeneous
-- hosting providers (commercial forges like GitHub, community forges like GitLab/Framagit/Disroot,
-- and sovereign self-hosted instances like Forgejo/Woodpecker/Radicle).
--
-- == Note [Forge-Tiered CI Resource Allocation and Static Gate Partitioning]
-- [tag:note-forge-tiered-ci]
--
-- Modern Haskell toolchains impose heavy compute and memory demands. Compiling
-- an interconnected multi-package workspace under GHC 9.14 with Template Haskell,
-- unboxed primitive arrays, and advanced type families requires multi-gigabyte RAM
-- footprints and significant CPU time.
--
-- Commercial hosting providers (e.g., GitHub Actions) provide high-capacity
-- container runners equipped with 4+ virtual CPUs, 16 GB RAM, generous monthly
-- compute allowances, and global artifact caching services (@actions/cache@).
-- Conversely, community-run and self-hosted forges (e.g., Framagit, Disroot,
-- Codeberg, sourcehut) operate on modest, shared virtual servers where running
-- a full GHC compilation pipeline on every push triggers runner timeouts, CPU
-- throttling, and out-of-memory kernel kills (OOM 137).
--
-- To achieve universal verification without depleting community resources or
-- failing due to runner memory constraints, Gachi establishes an __asymmetric
-- forge-tiered CI matrix__:
--
-- 1.  __High-Resource Commercial Runners ('TierHighResource'):__
--     Allocated to GitHub Actions (@.github/workflows/ci.yml@) and dedicated
--     enterprise Forgejo instances. Executes the complete, heavyweight physical
--     verification suite:
--     * Installs system runtime dependencies (bubblewrap, sqlite3, z3).
--     * Configures AppArmor namespace profiles for bubblewrap container isolation.
--     * Deploys pinned GHC (9.14.1) and Cabal (3.18.1.0) toolchains.
--     * Restores cryptographic Cabal store caches (@~/.cabal/store@, @dist-newstyle@).
--     * Compiles all workspace packages with @--enable-tests@.
--     * Executes HLint static analysis under the zero-hint policy.
--     * Executes all unit, property, and integration test suites.
--     * Verifies comment density thresholds via @./bin/<project>-cloc --check@.
--     * Executes the turnkey five-gate script: @./bin/<project>-verify@.
--
-- 2.  __Resource-Constrained Community Runners ('TierLightweightStatic'):__
--     Allocated to community GitLab instances (Framagit, Disroot: @.gitlab-ci.yml@),
--     Woodpecker CI (@.woodpecker.yml@), and Radicle local verification.
--     Executes fast, deterministic static analysis gates inside a minimal
--     container (@debian:bookworm-slim@) without GHC compilation:
--     * Installs lightweight utilities (curl, git, python3) and Tagref binary.
--     * Verifies Tagref cross-reference integrity (0 dangling references).
--     * Verifies Markdown link integrity and anchor slug resolution (0 broken links).
--     * Verifies in-code comment density thresholds (@bin/<project>-cloc --check@).
--     * Finishes execution in < 15 seconds with < 100 MB memory footprint.
--
-- This division guarantees that community infrastructure remains protected
-- from resource starvation while ensuring every repository maintains zero broken
-- links, zero dangling reference tags, and zero documentation drift on every commit.
--
-- == Economic & Operational Invariants
--
-- The forge-tiered CI matrix adheres to four non-negotiable operational rules:
--
-- * __Purity & Determinism:__ CI configuration files are synthesized purely from
--   the project specification ('Project') and CI specification ('CISpec').
--   No ambient environment variables, timestamps, or network requests are consulted.
--
-- * __Zero Dangling Pointers:__ Every script reference within synthesized CI files
--   (such as @./bin/<project>-verify@ or @./bin/<project>-tagref@) resolves
--   to an executable script generated by the Gachi scaffolding engine.
--
-- * __Cache Key Hermeticity:__ Cache keys on high-resource runners incorporate
--   cryptographic hashes of @cabal.project@ and all @**/*.cabal@ package files,
--   ensuring caches invalidate immediately upon dependency or compiler changes.
--
-- * __Sandbox Isolation:__ High-resource runners execute sandboxed test harnesses
--   under Bubblewrap (@bwrap@). To prevent Ubuntu 24.04 AppArmor user namespace
--   restrictions from aborting builds, synthesized workflows explicitly configure
--   unprivileged user namespace allowances and AppArmor profiles.
--
-- = Worked Example: High-Resource Workflow Generation
--
-- >>> import Gachi.Schema.Project (defaultProject, Author(..))
-- >>> import Gachi.Sync.CI
-- >>> let auth = Author "Nadia Yvette Chambers" "nadia.yvette.chambers@ik.me"
-- >>> let proj = defaultProject "gongju" auth
-- >>> let githubWf = generateGitHubWorkflow defaultGitHubSpec proj
-- >>> "cabal build all --enable-tests" `Data.Text.isInfixOf` githubWf
-- True
-- >>> "ubuntu-latest" `Data.Text.isInfixOf` githubWf
-- True
--
-- = Worked Example: Lightweight Community Workflow Generation
--
-- >>> let gitlabWf = generateGitLabWorkflow defaultGitLabSpec proj
-- >>> "debian:bookworm-slim" `Data.Text.isInfixOf` gitlabWf
-- True
-- >>> "./bin/gongju-tagref" `Data.Text.isInfixOf` gitlabWf
-- True
-- >>> "cabal build" `Data.Text.isInfixOf` gitlabWf
-- False
