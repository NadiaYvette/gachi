-- | Converts a 'CISpec' into a canonical 'StandardAsset' in 'CategoryCIWorkflow'.
--
-- Sets requirement flags:
-- * GitHub (@.github/workflows/ci.yml@) and GitLab (@.gitlab-ci.yml@) are mandatory ('assetRequired' = True).
-- * Ancillary forges (Woodpecker, Forgejo, Radicle) are optional ('assetRequired' = False).
forgeAssetForSpec :: CISpec -> StandardAsset
forgeAssetForSpec spec =
  let path = ciWorkflowPath spec
      -- Mandatory assets enforced across every ecosystem repository
      isReq = path `elem` [".github/workflows/ci.yml", ".gitlab-ci.yml"]
      -- Human-readable asset description
      desc = case ciForge spec of
        ForgeGitHub     -> "High-resource GitHub Actions workflow running complete physical gates"
        ForgeGitLab     -> "Lightweight GitLab CI workflow for resource-constrained community forges"
        ForgeWoodpecker -> "Lightweight Woodpecker CI workflow for Forgejo/Gitea runners"
        ForgeForgejo    -> "Self-hosted Forgejo Actions workflow running containerized verification"
        ForgeRadicle    -> "Radicle sovereign peer-to-peer verification pipeline"
  in StandardAsset
    { assetPath        = path
    , assetCategory    = CategoryCIWorkflow
    , assetRequired    = isReq
    , assetExecutable  = False
    , assetDescription = desc
    , assetGenerator   = generateWorkflow spec
    }

-- | Synthesizes a list of 'StandardAsset' records from a collection of 'CISpec' configurations.
--
-- Maps each specification into a standard matrix asset ready for auditing and propagation.
synthesizeCIAssets :: [CISpec] -> [StandardAsset]
synthesizeCIAssets = map forgeAssetForSpec

-- | The canonical list of standard CI workflow assets registered across all ecosystem checkouts.
--
-- Encompasses GitHub Actions, GitLab CI, and Woodpecker CI pipelines.
canonicalCIAssets :: [StandardAsset]
canonicalCIAssets = synthesizeCIAssets canonicalForgeSpecs
