-- | Pure dispatcher synthesizing the appropriate CI configuration text for a 'CISpec'.
--
-- Evaluates the target forge platform and invokes the corresponding deterministic generator.
generateWorkflow :: CISpec -> Project -> Text
generateWorkflow spec proj = case ciForge spec of
  ForgeGitHub     -> generateGitHubWorkflow spec proj
  ForgeGitLab     -> generateGitLabWorkflow spec proj
  ForgeWoodpecker -> generateWoodpeckerWorkflow spec proj
  ForgeForgejo    -> generateForgejoWorkflow spec proj
  ForgeRadicle    -> generateRadicleWorkflow spec proj

-- | Generates GitHub Actions workflow configuration (@.github/workflows/ci.yml@).
--
-- Implements the high-resource physical verification pipeline:
--
-- 1.  __Checkout Step:__
--     Uses @actions/checkout@v4@ to clone the repository with full git history.
--
-- 2.  __Tagref Installation & Check:__
--     Downloads the authoritative Tagref binary and executes @./bin/<project>-tagref@
--     to verify that zero dangling reference tags or duplicate tag definitions exist.
--
-- 3.  __Markdown Link & Anchor Gate:__
--     Executes @./bin/<project>-linkcheck@ to verify 100% of intra-corpus relative
--     links and section heading anchors across all markdown documentation files.
--
-- 4.  __System Dependencies & AppArmor Setup:__
--     Installs system runtime libraries (@bubblewrap@, @sqlite3@, @z3@).
--     Configures unconfined AppArmor profile for Bubblewrap (@bwrap@) to enable
--     unprivileged user namespace creation on Ubuntu 24.04 runner environments.
--
-- 5.  __Git Submodule Protocol Rewriting:__
--     Configures Git to rewrite @git@github.com:@ SSH URLs to HTTPS for clean submodule pulls.
--
-- 6.  __Haskell Toolchain Provisioning:__
--     Invokes @haskell-actions/setup@v2@ with pinned GHC (9.14.1) and Cabal (3.18.1.0).
--
-- 7.  __HLint Static Analysis Installation:__
--     Installs the recommended HLint binary via GHCup and runs under zero-hint cleanliness.
--
-- 8.  __Cryptographic Artifact Caching:__
--     Invokes @actions/cache@v4@ caching @~/.cabal/store@ and @dist-newstyle@ keyed on
--     the combined cryptographic hash of @cabal.project@ and all @**/*.cabal@ manifests.
--
-- 9.  __Compilation & Test Build:__
--     Executes @cabal build all --enable-tests@ compiling all workspace packages and test suites.
--
-- 10. __Comment Density Audit:__
--     Executes @./bin/<project>-cloc --check@ enforcing documentation thresholds.
--
-- 11. __Turnkey Verification Harness:__
--     Executes @./bin/<project>-verify@ ensuring all 5 physical gates pass in unison.
generateGitHubWorkflow :: CISpec -> Project -> Text
generateGitHubWorkflow spec proj =
  let pName = projectName proj
      ghcVer = ciGhcVersion spec
      cabalVer = ciCabalVersion spec
      deps = T.unwords (ciSystemDependencies spec)
  in T.unlines
    [ -- SPDX License identifier declaring legal terms
      "# SPDX-License-Identifier: EUPL-1.2"
      -- Canonical repository metadata comment
    , "# Canonical GitHub Actions CI Workflow for " <> pName
      -- Cross-reference pointer grounding the Note in the CI asset
    , "# Note [Forge-Tiered CI Resource Allocation and Static Gate Partitioning] [ref:note-forge-tiered-ci]"
    , ""
      -- Top-level workflow descriptive name
    , "name: CI Verification Harness"
    , ""
      -- Trigger definitions: executed on push and pull-request events targeting master
    , "on:"
    , "  push:"
    , "    branches: [ master ]"
    , "  pull_request:"
    , "    branches: [ master ]"
    , ""
      -- Job definition block
    , "jobs:"
    , "  verify:"
    , "    name: Tagref & Verification Gates"
      -- Host runner operating system targeting Ubuntu LTS
    , "    runs-on: ubuntu-latest"
    , "    steps:"
      -- Step 1: Check out git working tree
    , "      - name: Check out repository"
    , "        uses: actions/checkout@v4"
    , ""
      -- Step 2: Download and install Tagref cross-reference binary
    , "      - name: Install Tagref"
    , "        run: |"
    , "          mkdir -p \"${HOME}/.local/bin\""
    , "          PREFIX=\"${HOME}/.local/bin\" curl https://raw.githubusercontent.com/stepchowfun/tagref/main/install.sh -LSfs | sh"
    , "          echo \"${HOME}/.local/bin\" >> $GITHUB_PATH"
    , ""
      -- Step 3: Run static Tagref verification gate
    , "      - name: Verify Tagref Cross-References"
    , "        run: ./bin/" <> pName <> "-tagref"
    , ""
      -- Step 4: Run intra-corpus Markdown hyperlink and heading anchor verification
    , "      - name: Verify Markdown Links & Anchors"
    , "        run: ./bin/" <> pName <> "-linkcheck"
    , ""
      -- Step 5: Install runtime system dependencies and configure AppArmor sandbox profiles
    , "      - name: Install System Dependencies"
    , "        run: |"
    , "          sudo apt-get update"
    , "          sudo apt-get install -y " <> deps
      -- Disable Ubuntu 24.04 kernel restriction on unprivileged user namespaces
    , "          sudo sysctl -w kernel.apparmor_restrict_unprivileged_userns=0 2>/dev/null || true"
      -- Create unconfined AppArmor profile for Bubblewrap if profile directory exists
    , "          if [ -d /etc/apparmor.d ]; then"
    , "            printf 'abi <abi/4.0>,\\ninclude <tunables/global>\\nprofile bwrap /usr/bin/bwrap flags=(unconfined) {\\n    userns,\\n    include if exists <local/bwrap>\\n}\\n' | sudo tee /etc/apparmor.d/bwrap >/dev/null || true"
    , "            sudo apparmor_parser -r /etc/apparmor.d/bwrap 2>/dev/null || true"
    , "          fi"
    , ""
      -- Step 6: Rewrite SSH Git submodule URLs to HTTPS to avoid unauthenticated SSH failures
    , "      - name: Configure Git for HTTPS submodules"
    , "        run: git config --global url.\"https://github.com/\".insteadOf \"git@github.com:\""
    , ""
      -- Step 7: Configure pinned GHC and Cabal toolchain via official Haskell action
    , "      - name: Set up Haskell Toolchain"
    , "        uses: haskell-actions/setup@v2"
    , "        with:"
    , "          ghc-version: '" <> ghcVer <> "'"
    , "          cabal-version: '" <> cabalVer <> "'"
    , ""
      -- Step 8: Install HLint binary
    , "      - name: Install HLint"
    , "        run: |"
